#!/usr/bin/env ruby
# frozen_string_literal: true

require 'cgi'
require 'date'
require 'yaml'

Dir.chdir(File.expand_path('..', __dir__))

FIELDS = %w[id title slug difficulty patterns solved_at time_complexity
            space_complexity leetcode_url status].freeze
DIFFICULTIES = %w[easy medium hard].freeze
STATUSES = %w[planned in-progress solved review].freeze
SLUG = /\A[a-z0-9]+(?:-[a-z0-9]+)*\z/
PROGRESS = /^<!-- progress:start -->\n.*?^<!-- progress:end -->$/m

def markdown_text(value)
  CGI.escapeHTML(value.to_s).gsub(/[\[\]|*_\x60\\~]/) { |char| "&##{char.ord};" }
end

def read_problem(file)
  data = YAML.safe_load(File.read(file, encoding: 'UTF-8'), permitted_classes: [Date])
  abort "#{file}: expected fields #{FIELDS.join(', ')}" unless
    data.is_a?(Hash) && (FIELDS - data.keys).empty?

  id = data['id']
  slug = data['slug']
  patterns = data['patterns']
  date = data['solved_at']
  unless id.is_a?(Integer) && id.positive? && slug.is_a?(String) && SLUG.match?(slug) &&
         patterns.is_a?(Array) && patterns.all? { |tag| tag.is_a?(String) && SLUG.match?(tag) } &&
         DIFFICULTIES.include?(data['difficulty']) && STATUSES.include?(data['status']) &&
         (date.nil? || date.to_s.match?(/\A\d{4}-\d{2}-\d{2}\z/)) &&
         %w[title time_complexity space_complexity].all? { |key|
           data[key].is_a?(String) && !data[key].strip.empty? && !data[key].match?(/[\r\n]/)
         } && data['leetcode_url'] == "https://leetcode.com/problems/#{slug}/"
    abort "#{file}: invalid metadata (see CONTRIBUTING.md)"
  end

  folder = format('%04d-%s', id, slug)
  abort "#{file}: expected folder #{folder}" unless File.basename(File.dirname(file)) == folder

  data.merge('number' => format('%04d', id), 'folder' => folder)
rescue Psych::Exception => e
  abort "#{file}: #{e.message}"
end

def problem_link(problem, language, prefix = '')
  label = "#{problem['number']} #{markdown_text(problem['title'])}"
  "[#{label}](#{prefix}problems/#{problem['folder']}/README.#{language}.md)"
end

problems = Dir.glob('problems/*/meta.yml').map { |file| read_problem(file) }
              .sort_by { |problem| problem['id'] }
abort 'Problem IDs must be unique.' unless problems.map { |problem| problem['id'] }.uniq.size == problems.size

by_pattern = Hash.new { |hash, tag| hash[tag] = [] }
problems.each do |problem|
  problem['patterns'].uniq.each { |tag| by_pattern[tag] << problem }
end

editions = {
  'en' => {
    filename: 'README.md', index_title: 'Pattern index', home: 'Progress',
    headers: %w[Problem Difficulty Patterns Status Solved],
    difficulties: %w[Easy Medium Hard],
    statuses: ['Planned', 'In progress', 'Solved', 'Review']
  },
  'fa' => {
    filename: 'README.fa.md', index_title: 'فهرست الگوها', home: 'پیشرفت',
    headers: ['مسئله', 'سختی', 'الگوها', 'وضعیت', 'تاریخ حل'],
    difficulties: %w[آسان متوسط سخت],
    statuses: ['برنامه‌ریزی‌شده', 'در حال حل', 'حل‌شده', 'مرور']
  }
}

outputs = {}
editions.each do |language, edition|
  root = edition[:filename]
  body = File.read(root, encoding: 'UTF-8')
  abort "#{root}: expected exactly one progress block" unless body.scan(PROGRESS).size == 1

  table = ["| #{edition[:headers].join(' | ')} |", "| #{(['---'] * edition[:headers].size).join(' | ')} |"]
  problems.each do |problem|
    difficulty = edition[:difficulties].fetch(DIFFICULTIES.index(problem['difficulty']))
    status = edition[:statuses].fetch(STATUSES.index(problem['status']))
    tags = problem['patterns'].uniq.map { |tag| "`#{tag}`" }.join(', ')
    cells = [problem_link(problem, language), difficulty, tags.empty? ? '—' : tags,
             status, problem['solved_at'] || '—']
    table << "| #{cells.join(' | ')} |"
  end
  progress = ["<!-- progress:start -->", '', *table, '', '<!-- progress:end -->']
  outputs[root] = body.sub(PROGRESS) { progress.join("\n") }

  index = ["# #{edition[:index_title]}", '', "[#{edition[:home]}](../#{root})",
           '', '<!-- Generated by scripts/regenerate.rb. -->']
  by_pattern.sort.each do |tag, entries|
    index.push('', "## `#{tag}`", '')
    entries.each { |problem| index << "- #{problem_link(problem, language, '../')}" }
  end
  outputs["patterns/#{root}"] = index.join("\n") + "\n"
end

outputs.each { |path, content| File.write(path, content, encoding: 'UTF-8') }
